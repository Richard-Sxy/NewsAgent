/* Browser acceptance against an isolated validation DB, never the user's queue. */
const { chromium } = require(process.env.NEWSAGENT_PLAYWRIGHT_PATH || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const base = process.argv[2] || 'http://127.0.0.1:8878';
  if (new URL(base).hostname !== '127.0.0.1' || new URL(base).port !== '8878') throw new Error('Use the isolated UI validation server on 127.0.0.1:8878');
  const out = path.resolve(__dirname, '../../output/news-events-annual-20261027/lab-validation');
  fs.mkdirSync(out, {recursive:true});
  const browser = await chromium.launch({channel:'chrome',headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(String(e)));
  try {
    await page.goto(base, {waitUntil:'networkidle'});
    await page.locator('#run-content').waitFor({state:'visible'});
    assert.match(await page.locator('#query-count').innerText(), /30/);
    const initialTitle = await page.locator('#article-title').innerText();
    assert.ok(initialTitle.length>4);
    assert.equal(await page.locator('input[name=relevance]:checked').count(),0);
    assert.equal(await page.locator('.score-detail').getAttribute('open'),null);
    await page.locator('#reviewer').fill('UI-SMOKE-ONLY-NOT-GOLD');
    await page.locator('#judgment-notes').fill('仅浏览器保存验收副本，不进入人工金标。');
    await page.locator('input[value=unsure]').check();
    await page.locator('#save').click();
    await page.waitForFunction(()=>document.querySelector('#save-status').textContent.includes('已保存'));
    await page.reload({waitUntil:'networkidle'});
    await page.locator('#run-content').waitFor({state:'visible'});
    assert.equal(await page.locator('#article-title').innerText(),initialTitle);
    assert.equal(await page.locator('input[value=unsure]').isChecked(),true);
    assert.match(await page.locator('#judgment-notes').inputValue(), /验收副本/);
    await page.locator('input[value=partial]').check();
    await page.locator('#save-next').click();
    await page.waitForFunction(()=>document.querySelector('#candidate-position').textContent.includes('2 / 10'));
    assert.equal(await page.locator('input[name=relevance]:checked').count(),0);
    await page.locator('.trace-card > summary').click();
    assert.match(await page.locator('#tier-summary').innerText(),/冷层/);
    await page.screenshot({path:path.join(out,'annotation-desktop.png'),fullPage:true});
    const snapshot = await (await page.request.get(base+'/api/export')).json();
    fs.writeFileSync(path.join(out,'ui-smoke-export.json'),JSON.stringify(snapshot,null,2));
    const rows = snapshot.runs.flatMap(r=>r.candidates).filter(c=>c.judgment.label!==null);
    assert.equal(rows.length,1);
    assert.equal(rows[0].judgment.label,'partial');
    assert.equal(rows[0].judgment.revision,2);
    await page.locator('#custom-query').fill('神舟二十二号应急发射有哪些相关报道？');
    await page.locator('#search-button').click();
    await page.waitForFunction(()=>document.querySelector('#query-text').textContent.includes('神舟二十二号应急发射有哪些相关报道'),null,{timeout:60000});
    assert.match(await page.locator('#candidate-position').innerText(), /10/);
    assert.equal(await page.locator('input[name=relevance]:checked').count(),0);
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(out,'annotation-mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
    assert.deepEqual(errors,[]);
    const result={status:'passed',checks:['30 queries visible','no preset labels','scores collapsed','save to server','reload recovery','revision increment','next article blank','tier trace visible','export judgment revision','real custom semantic search','mobile width','no JS errors'],test_database:'validation copy only',user_queue_untouched:true};
    fs.writeFileSync(path.join(out,'browser-check.json'),JSON.stringify(result,null,2));
    console.log(JSON.stringify(result));
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
